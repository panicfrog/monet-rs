#!/bin/zsh
# Vendors the monet crates into this package (vendor/) — the copy the
# consumer app's aggregate build actually compiles. The repo's crates/
# stays the single source of truth: host tests, conformance batteries and
# lint all run there. Run this after editing any crate, before building the
# app — the aggregate build resolves these paths from node_modules, so path
# deps out of the package cannot work there.
#
# The vendored crates keep their `x.workspace = true` inheritance, which
# would dangle outside the repo. The mirror tables (copied verbatim from the
# repo root, from [workspace.package] to EOF) must live in TWO places:
#
#   vendor/Cargo.toml   — the walk-up root when a vendored crate is loaded
#                         directly (tests, tooling)
#   this crate's own [workspace] section — cargo binds a path dependency
#                         that lives inside a workspace root's tree to that
#                         root, and the vendored crates are path deps of this
#                         crate. Empirically: without the tables there, the
#                         app's aggregate build fails inheriting `edition`
#                         from this manifest's [workspace].
#
# Both are regenerated by this script; do not edit by hand.

set -euo pipefail

ROOT=${0:A:h}/../../..
CRATES=(monet-core monet-tls monet-rustls monet-ws monet-urlsession)

# ---- 1. rsync the crate sources, then strip [dev-dependencies] ----
# The dev-deps reference crates that are not vendored (monet-conformance is
# the shared test battery, a dev-dep of the transports) — cargo resolves
# them into the lockfile anyway and would fail on the dangling path. The
# app's aggregate build never compiles tests, so the vendored copies drop
# the dev-deps sections entirely. Everything else stays byte-identical.
for crate in $CRATES; do
  print "== vendoring ${crate}"
  rsync -a --delete ${ROOT}/crates/${crate}/ vendor/${crate}/
  awk '
    /^\[/ {
      skip = ($0 ~ /^\[dev-dependencies\]$/ || $0 ~ /^\[target\.[^]]*\.dev-dependencies\]$/)
    }
    !skip
  ' vendor/${crate}/Cargo.toml > vendor/${crate}/Cargo.toml.tmp &&
  mv vendor/${crate}/Cargo.toml.tmp vendor/${crate}/Cargo.toml
done

# ---- 2. generate the mirror workspaces ----
print "== generating vendor/Cargo.toml and this crate's [workspace] section"
{
  print '# GENERATED by scripts/sync-vendor.sh — the mirror workspace the'
  print '# vendored monet crates resolve their `x.workspace = true` inheritance'
  print '# against (tables copied verbatim from the repo root). Regenerated on'
  print '# every sync; do not edit by hand.'
  print '[workspace]'
  print 'resolver = "3"'
  print 'members = ['
  for crate in $CRATES; do
    print "  \"${crate}\","
  done
  print ']'
  print ''
  sed -n '/^\[workspace\.package\]/,$p' ${ROOT}/Cargo.toml
} > vendor/Cargo.toml

TABLES=$(sed -n '/^\[workspace\.package\]/,$p' ${ROOT}/Cargo.toml)

python3 - "$TABLES" <<'PY'
import pathlib
import re
import sys

tables = sys.argv[1]
pkg = pathlib.Path('Cargo.toml')
content = pkg.read_text()

# The generated region: the marker through the [workspace] header and every
# [workspace.*] table, up to the next section (idempotent on re-runs).
marker = '# GENERATED-BY sync-vendor.sh (workspace section) — do not edit:'
start = content.index(marker)
m = re.search(r'^\[(?!workspace)[^\]]*\]', content[start:], re.MULTILINE)
end = start + m.start()
replacement = (
    marker
    + """ the vendored crates inherit their
# `x.workspace = true` against these tables (copied verbatim from the repo
# root) when cargo binds them to this crate's [workspace] — see the script
# header for the two binding contexts.
[workspace]

"""
    + tables
    + "\n\n"
)
pkg.write_text(content[:start] + replacement + content[end:])
PY

print '== vendor synced (source of truth: crates/ — run host tests there)'
